out.push("insert into public.homepage_sections (key, title_ar, title_en, sort_order, data) values");
out.push(sections.map(([k, ar, en, i, d]) => `  (${q(k)}, ${q(ar || null)}, ${q(en || null)}, ${i}, ${q(JSON.stringify(d))}::jsonb)`).join(",\n") + ";");

